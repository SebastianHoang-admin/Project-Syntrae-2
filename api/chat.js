function buildFallbackPersonaReply(latestUserMessage) {
  const text = String(latestUserMessage || '').trim();
  const lower = text.toLowerCase();

  const asksChance =
    lower.includes('chance') ||
    lower.includes('probability') ||
    lower.includes('how likely');
  const asksInvite =
    /\b(go|join|eat|dinner|lunch|restaurant|gym|swim|date|hang out|meet)\b/i.test(lower);

  if (asksChance) {
    return 'Based on this persona profile, the chance looks moderate right now. The best next step is a low-pressure invite with clear timing.';
  }
  if (asksInvite) {
    return 'Based on this persona profile, that invite could work, but timing and framing matter. A specific, low-pressure plan is most likely to land well.';
  }
  return 'Syntrae AI is an analytical tool, not the real person. Share a specific action and this profile can estimate chance and suggest the best approach.';
}

