async function fetchJson(url, headers) {
  const response = await fetch(url, { method: 'GET', headers });
  const body = await response.json().catch(() => ({}));
  return { ok: response.ok, status: response.status, body };
}

async function fetchSupabaseUser(supabaseUrl, anonKey, accessToken) {
  return fetchJson(`${supabaseUrl}/auth/v1/user`, {
    apikey: anonKey,
    Authorization: `Bearer ${accessToken}`
  });
}

async function fetchUserProfile(supabaseUrl, anonKey, accessToken, userId) {
  const url = `${supabaseUrl}/rest/v1/user_profiles?user_id=eq.${encodeURIComponent(userId)}&select=user_id,first_name,last_name,occupation,organization,location,profile&limit=1`;
  const { ok, body } = await fetchJson(url, {
    apikey: anonKey,
    Authorization: `Bearer ${accessToken}`
  });
  if (!ok || !Array.isArray(body) || !body.length) return null;
  return body[0];
}

async function fetchPersonaRow(supabaseUrl, anonKey, accessToken, userId, personaKey) {
  const filters = [
    `user_id=eq.${encodeURIComponent(userId)}`,
    `select=id,persona_key,name,state,traits,profile`,
    `order=updated_at.desc`,
    'limit=1'
  ];
  if (personaKey) filters.unshift(`persona_key=eq.${encodeURIComponent(personaKey)}`);
  const url = `${supabaseUrl}/rest/v1/personas?${filters.join('&')}`;
  const { ok, body } = await fetchJson(url, {
    apikey: anonKey,
    Authorization: `Bearer ${accessToken}`
  });
  if (!ok || !Array.isArray(body) || !body.length) return null;
  return body[0];
}

async function fetchPersonaSummaries(supabaseUrl, anonKey, accessToken, userId) {
  const url = `${supabaseUrl}/rest/v1/personas?user_id=eq.${encodeURIComponent(
    userId
  )}&select=persona_key,name,updated_at&order=updated_at.desc&limit=25`;
  const { ok, body } = await fetchJson(url, {
    apikey: anonKey,
    Authorization: `Bearer ${accessToken}`
  });
  if (!ok || !Array.isArray(body)) return [];
  return body.map((row) => ({
    persona_key: sanitizePersonaKey(row?.persona_key || ''),
    name: String(row?.name || '').trim() || sanitizePersonaKey(row?.persona_key || ''),
    updated_at: row?.updated_at || null
  }));
}

function fallbackUserProfileFromMetadata(user) {
  const meta = user?.user_metadata || {};
  return {
    first_name: meta.first_name || '',
    last_name: meta.last_name || '',
    occupation: meta.occupation || '',
    organization: meta.organization || '',
    location: meta.location || '',
    profile: {}
  };
}

function buildPersonaProfile(personaRow) {
  if (!personaRow || typeof personaRow !== 'object') return {};
  const state = personaRow.state && typeof personaRow.state === 'object' ? personaRow.state : {};
  const derivedCriticalFactors = extractCriticalFactorsFromState(state);
  if (personaRow.profile && typeof personaRow.profile === 'object') {
    if (personaRow.profile.critical_factors) return personaRow.profile;
    if (Object.keys(derivedCriticalFactors).length) {
      return {
        ...personaRow.profile,
        critical_factors: derivedCriticalFactors
      };
    }
    return personaRow.profile;
  }
  const traits = personaRow.traits && typeof personaRow.traits === 'object' ? personaRow.traits : {};
  return {
    personaName: state.personaName || personaRow.name || '',
    identityLayers: state.identityLayers || {},
    traits,
    extras: state.extras || {},
    usersInput: state.usersInput || '',
    critical_factors: derivedCriticalFactors
  };
}

const CRITICAL_FIELD_ID_TO_KEY = Object.freeze({
  L6_S1_F1: 'physical_incapability',
  L6_S1_F2: 'hard_no_activities',
  L6_S1_F3: 'absolute_boundaries',
  L6_S2_F1: 'favorite_dishes',
  L6_S2_F2: 'favorite_colors',
  L6_S2_F3: 'preferred_activities',
  L6_S3_F1: 'extreme_dislikes',
  L6_S3_F2: 'strong_likes'
});

function extractCriticalFactorsFromState(state) {
  const answers = state?.answers && typeof state.answers === 'object' ? state.answers : {};
  const critical = {};
  Object.entries(answers).forEach(([questionId, answer]) => {
    if (!answer || answer.type !== 'free') return;
    const text = String(answer.text || '').trim();
    if (!text) return;
    const fieldName = String(answer.fieldName || '').trim();
    const key = fieldName || CRITICAL_FIELD_ID_TO_KEY[questionId] || '';
    if (!key) return;
    critical[key] = text;
  });
  return critical;
}

async function requestCompletion({ apiKey, model, messages, responseFormat }) {
  const payload = {
    model,
    messages
  };
  if (responseFormat && typeof responseFormat === 'object') {
    payload.response_format = responseFormat;
  }

  const openaiRes = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${apiKey}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify(payload)
  });

  const data = await openaiRes.json().catch(() => ({}));
  if (!openaiRes.ok) {
    const message = data?.error?.message || data?.error || 'OpenAI request failed';
    const err = new Error(message);
    err.status = openaiRes.status;
    throw err;
  }

  return data;
}

async function maybeRunTaskProbabilitySimulation({
  latestUserMessage,
  personaProfile,
  apiKey,
  model,
}) {
  if (!shouldRunTaskProbability(latestUserMessage)) return null;

  const deterministic = classifyDcRangeDeterministic({
    taskText: latestUserMessage,
    personaProfile,
  });
  const criticalOverride = detectCriticalFactorOverride({
    taskText: latestUserMessage,
    personaProfile,
    taskSignals: deterministic.signals
  });
  let selectedRange = deterministic.range;
  let classifier = {
    source: 'deterministic_traits',
    rangeId: deterministic.range.id,
    confidence: null,
    rationale: 'Deterministic trait-based range classification.'
  };

  if (criticalOverride.fixedDC != null) {
    selectedRange = selectRangeById(criticalOverride.fixedDC <= 20 ? 1 : 5);
    classifier = {
      source: 'critical_override',
      rangeId: selectedRange.id,
      confidence: 1,
      rationale:
        criticalOverride.outcome === 'conflict'
          ? 'Critical factor contradiction detected. Fixed DC=90.'
          : 'Critical factor support detected. Fixed DC=10.'
    };
  } else {
    const classifierModel = resolveEnv(['OPENAI_DC_CLASSIFIER_MODEL']) || model;
    if (apiKey && classifierModel) {
      try {
        const classifyPrompt = buildDcClassifierPrompt({
          taskText: latestUserMessage,
          personaProfile,
          deterministic
        });
        const classifyData = await requestCompletion({
          apiKey,
          model: classifierModel,
          responseFormat: { type: 'json_object' },
          messages: [
            { role: 'system', content: 'Return valid JSON only.' },
            { role: 'user', content: classifyPrompt }
          ]
        });
        const raw = classifyData?.choices?.[0]?.message?.content || '{}';
        const parsed = parseJsonObject(raw) || {};
        const pickedRangeId = normalizeRangeIdFromModelOutput(parsed, deterministic.range.id);
        selectedRange = selectRangeById(pickedRangeId);
        classifier = {
          source: 'llm_plus_traits',
          rangeId: pickedRangeId,
          confidence: Number.isFinite(Number(parsed?.confidence))
            ? Math.max(0, Math.min(1, Number(parsed.confidence)))
            : null,
          rationale: String(parsed?.rationale || '').trim() || 'Model-selected range from task/persona context.'
        };
      } catch (_) {
        // Fallback to deterministic classifier.
      }
    }
  }

  const chosenDC =
    criticalOverride.fixedDC != null ? criticalOverride.fixedDC : drawDcInRange(selectedRange, Math.random);
  const trial = simulateDcPassRate({
    dc: chosenDC,
    rolls: 100,
    rng: Math.random
  });

  return {
    taskText: latestUserMessage,
    range: selectedRange,
    chosenDC,
    classifier,
    deterministicBaseline: deterministic,
    criticalOverride,
    trial
  };
}

module.exports = async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).json({ error: 'POST only' });

  const apiKey = resolveEnv(['OPENAI_API_KEY', 'OPENAI_API_KEY_LOCAL', 'OPENAI_KEY']);
  if (!apiKey) {
    return res.status(500).json({
      error: 'Missing OpenAI key. Set OPENAI_API_KEY (or OPENAI_API_KEY_LOCAL) in local env.'
    });
  }

  const { messages, personaKey } = req.body || {};
  if (!Array.isArray(messages)) return res.status(400).json({ error: 'messages must be an array' });

  const supabaseUrl = resolveEnv(['SUPABASE_URL']);
  const supabaseAnonKey = resolveEnv(['SUPABASE_ANON_KEY', 'SUPABASE_ANON_KEY_LOCAL']);
  const authHeader = String(req.headers.authorization || '');
  const accessToken = authHeader.startsWith('Bearer ') ? authHeader.slice(7).trim() : '';

  let userProfile = {};
  let personaProfile = {};
  let accountPersonas = [];
  let activePersonaName = '';
  const safePersonaKey = sanitizePersonaKey(personaKey);

  if (supabaseUrl && supabaseAnonKey) {
    if (!accessToken) {
      return res.status(401).json({ error: 'Missing authenticated session token' });
    }

    const userResult = await fetchSupabaseUser(supabaseUrl, supabaseAnonKey, accessToken);
    if (!userResult.ok || !userResult.body?.id) {
      return res.status(401).json({ error: 'Invalid or expired session token' });
    }

    const user = userResult.body;
    const profileRow = await fetchUserProfile(supabaseUrl, supabaseAnonKey, accessToken, user.id);
    userProfile = profileRow || fallbackUserProfileFromMetadata(user);

    const personaRow = await fetchPersonaRow(
      supabaseUrl,
      supabaseAnonKey,
      accessToken,
      user.id,
      safePersonaKey
    );
    activePersonaName = personaRow?.name || '';
    personaProfile = buildPersonaProfile(personaRow);
    accountPersonas = await fetchPersonaSummaries(
      supabaseUrl,
      supabaseAnonKey,
      accessToken,
      user.id
    );
  }

  const systemPrompt = buildContextPrompt({
    userProfile,
    personaProfile,
    personaName: activePersonaName,
    personaKey: safePersonaKey,
    accountPersonas
  });

  const normalizedHistory = normalizeMessages(messages, activePersonaName);
  const latestUserMessage =
    [...normalizedHistory].reverse().find((msg) => msg.role === 'user')?.content || '';
  const methodProbe = isMethodProbe(latestUserMessage);
  const probabilityIntentDetected = shouldRunTaskProbability(latestUserMessage);

  const model = resolveEnv(['OPENAI_MODEL']) || 'gpt-5-nano';

  try {
    const taskProbabilitySim = await maybeRunTaskProbabilitySimulation({
      latestUserMessage,
      personaProfile,
      apiKey,
      model
    });

    const verification = {
      methodGuardApplied: false,
      probabilityIntentDetected,
      usedTaskProbabilitySimulation: Boolean(taskProbabilitySim),
      expectedPercent: taskProbabilitySim
        ? Number((taskProbabilitySim.trial.successProbability * 100).toFixed(1))
        : null,
      replyPercent: null,
      probabilityPercentMatch: null,
      probabilityReplyEnforced: false
    };

    if (methodProbe && !taskProbabilitySim) {
      verification.methodGuardApplied = true;
      return res.status(200).json({
        reply: buildMethodGuardReply({
          latestUserMessage,
          taskProbabilitySim: null
        }),
        usage: null,
        simulation: null,
        verification
      });
    }

    const finalMessages = [
      { role: 'system', content: systemPrompt },
      ...(taskProbabilitySim
        ? [{ role: 'system', content: buildTaskProbabilitySystemPrompt(taskProbabilitySim) }]
        : []),
      ...normalizedHistory
    ];

    const data = await requestCompletion({
      apiKey,
      model,
      messages: finalMessages
    });

    let reply = data?.choices?.[0]?.message?.content || 'No reply';
    let usage = data?.usage || null;

    if (hasPolicyBreak(reply, activePersonaName)) {
      const repaired = await requestCompletion({
        apiKey,
        model,
        messages: [
          { role: 'system', content: systemPrompt },
          ...(taskProbabilitySim
            ? [{ role: 'system', content: buildTaskProbabilitySystemPrompt(taskProbabilitySim) }]
            : []),
          {
            role: 'system',
            content: buildRepairPrompt({
              personaName: activePersonaName,
              personaKey: safePersonaKey
            })
          },
          {
            role: 'user',
            content: [
              'Latest user message:',
              latestUserMessage || '(none)',
              '',
              'Draft reply to rewrite:',
              reply
            ].join('\n')
          }
        ]
      });
      const repairedReply = repaired?.choices?.[0]?.message?.content || '';
      if (repairedReply) reply = repairedReply;
      usage = repaired?.usage || usage;
    }

    if (hasPolicyBreak(reply, activePersonaName)) {
      reply = buildFallbackPersonaReply(latestUserMessage);
    }

    if (taskProbabilitySim) {
      const expectedPercent = Number((taskProbabilitySim.trial.successProbability * 100).toFixed(1));
      const parsedReplyPercent = extractFirstPercentValue(reply);
      const matches =
        typeof parsedReplyPercent === 'number' &&
        Math.abs(parsedReplyPercent - expectedPercent) <= 0.1;

      verification.replyPercent = parsedReplyPercent;
      verification.probabilityPercentMatch = matches;
      verification.methodGuardApplied = methodProbe;

      if (!matches) {
        reply = buildVerifiedProbabilityReply(taskProbabilitySim, latestUserMessage, methodProbe);
        verification.probabilityReplyEnforced = true;
        verification.replyPercent = expectedPercent;
        verification.probabilityPercentMatch = true;
      } else if (methodProbe) {
        if (FORBIDDEN_METHOD_DISCLOSURE_RE.test(reply)) {
          reply = buildVerifiedProbabilityReply(taskProbabilitySim, latestUserMessage, true);
          verification.probabilityReplyEnforced = true;
          verification.replyPercent = expectedPercent;
          verification.probabilityPercentMatch = true;
        } else {
          reply = `${reply.trim()} ${buildMethodGuardReply({
            latestUserMessage,
            taskProbabilitySim
          })}`;
        }
      }
    }

    return res.status(200).json({
      reply,
      usage,
      simulation: taskProbabilitySim
        ? {
            mode: 'task_probability',
            selectedRange: taskProbabilitySim.range.label,
            chosenDC: taskProbabilitySim.chosenDC,
            criticalOverride: taskProbabilitySim.criticalOverride || null,
            successProbability: taskProbabilitySim.trial.successProbability,
            successCount: taskProbabilitySim.trial.successCount,
            totalRolls: taskProbabilitySim.trial.totalRolls
          }
        : null,
      verification
    });
  } catch (err) {
    const status = Number(err?.status) || 500;
    return res.status(status).json({ error: err?.message || 'OpenAI request failed' });
  }
};
