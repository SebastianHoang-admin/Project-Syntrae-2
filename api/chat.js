const PERSONA_KEY_RE = /[^a-z0-9_-]/g;
const IDENTITY_LEAK_RE =
  /\b(as an ai|i(?:\s*am|'m)\s+(?:an?\s+)?(?:ai|llm|language model|virtual assistant|assistant|software|program|chatbot|model))\b/i;
const VIRTUAL_LIMITATION_RE =
  /\b(i(?:\s*can(?:not|'t)|\s*won't)\s+(?:physically\s+)?(?:join|go|come|meet|be there|attend)|virtual\s+(?:assistant|buddy|coach|companion|dining|gym|swimming)|cannot\s+physically|can't\s+physically)\b/i;
const REAL_PERSON_CHAT_STYLE_RE =
  /\b(what should we chat about today|nice to reconnect|i can swing by|do you want me to come over|should we meet at yours|let me know what fits your schedule)\b/i;
const FIRST_PERSON_BIO_RE =
  /\b(i(?:'m| am)\s+\d{1,2}\b|i(?:'m| am)\s+(?:a|an)\s+(?:student|major|developer|engineer|employee)\b)\b/i;
const PROBABILITY_INTENT_RE = /\b(chance|probability|odds|how likely)\b/i;
const METHOD_DETAILS_RE = /\b(method|formula|logic|calculation|calculate|computed?|algorithm|dc|dice|roll|simulation|how did you get|how was this|how do you know|prove)\b/i;
const FORBIDDEN_METHOD_DISCLOSURE_RE =
  /\b(algorithm|dc|dice|roll|simulation|formula|calculation|computed?|weighting|gradient|optimizer|model internals?)\b/i;
const METHOD_CHALLENGE_RE =
  /\b(why\s+\d+(?:\.\d+)?%?|could be|should be|not\s+\d+(?:\.\d+)?%?|too low|too high|higher|lower)\b/i;
const DECISION_ASK_RE = /\b(would you|will you|can you|could you|are you open to|do you want to)\b/i;
const ACTIVITY_RE =
  /\b(go|join|eat|dinner|lunch|restaurant|bouldering|climb|hike|swim|gym|hang out|date|travel|meet|party|movie|coffee)\b/i;
const TRADE_SECRET_METHOD_PREFIXES = Object.freeze([
  "I can't share internal mechanics, but the estimate comes from Syntrae's proprietary system.",
  "The exact calculation details are confidential, but the percentage is generated by Syntrae's proprietary framework.",
  "I can't disclose internal scoring logic, but this result is produced by Syntrae's proprietary process.",
  "I can't open the internal formula, but the estimate is generated through Syntrae's private calibration system."
]);
const TRADE_SECRET_METHOD_REDIRECTS = Object.freeze([
  "If you want, I can re-check the chance with a different place, time, or message framing.",
  "If you want to push the odds up, I can run a revised scenario with a softer invite and clearer timing.",
  "If you share one concrete change, I can re-estimate and show whether the chance improves.",
  "If you want a better number, we can test a new scenario and compare results."
]);

function sanitizePersonaKey(value) {
  const normalized = String(value || '').trim().toLowerCase();
  if (!normalized) return '';
  const cleaned = normalized.replace(PERSONA_KEY_RE, '');
  return cleaned || '';
}

function hasRealPersonImpersonation(text, personaName) {
  const value = String(text || '').trim();
  if (!value) return false;
  const lower = value.toLowerCase();
  const safeName = String(personaName || '').trim().toLowerCase();
  if (safeName) {
    if (
      lower.includes(`i'm ${safeName}`) ||
      lower.includes(`i am ${safeName}`) ||
      lower.includes(`this is ${safeName}`)
    ) {
      return true;
    }
  }
  return FIRST_PERSON_BIO_RE.test(value) || REAL_PERSON_CHAT_STYLE_RE.test(value);
}

function hasPolicyBreak(text, personaName) {
  const value = String(text || '');
  if (!value) return false;
  return (
    IDENTITY_LEAK_RE.test(value) ||
    VIRTUAL_LIMITATION_RE.test(value) ||
    hasRealPersonImpersonation(value, personaName)
  );
}

function normalizeMessages(messages, personaName) {
  return messages
    .filter((msg) => {
      if (!msg || (msg.role !== 'user' && msg.role !== 'assistant')) return false;
      const content = String(msg.content || '').trim();
      if (!content) return false;
      // Drop prior assistant turns that violate tool policy to avoid reinforcement.
      if (msg.role === 'assistant' && hasPolicyBreak(content, personaName)) return false;
      return true;
    })
    .map((msg) => ({
      role: msg.role,
      content: String(msg.content || '').trim()
    }))
    .slice(-40);
}

function safeJson(value) {
  try {
    return JSON.stringify(value || {}, null, 2);
  } catch (_) {
    return '{}';
  }
}

function parseJsonObject(content) {
  if (content && typeof content === 'object' && !Array.isArray(content)) return content;
  if (typeof content !== 'string') return null;
  const stripped = content
    .trim()
    .replace(/^```json\s*/i, '')
    .replace(/^```\s*/i, '')
    .replace(/```$/i, '')
    .trim();
  try {
    return JSON.parse(stripped);
  } catch (_) {
    return null;
  }
}

function shouldRunTaskProbability(text) {
  const value = String(text || '').trim();
  if (!value) return false;
  if (PROBABILITY_INTENT_RE.test(value)) return true;
  return DECISION_ASK_RE.test(value) && ACTIVITY_RE.test(value);
}

function isMethodProbe(text) {
  const value = String(text || '').trim();
  if (!value) return false;
  return METHOD_DETAILS_RE.test(value);
}

function hashString32(str) {
  const value = String(str || '');
  let hash = 0;
  for (let i = 0; i < value.length; i += 1) {
    hash = (hash << 5) - hash + value.charCodeAt(i);
    hash |= 0;
  }
  return hash >>> 0;
}

function pickVariant(seedText, options) {
  if (!Array.isArray(options) || options.length === 0) return '';
  const idx = hashString32(seedText) % options.length;
  return options[idx];
}

function extractFirstPercentValue(text) {
  const value = String(text || '');
  const match = value.match(/(-?\d+(?:\.\d+)?)\s*%/);
  if (!match) return null;
  const parsed = Number(match[1]);
  return Number.isFinite(parsed) ? parsed : null;
}

function chanceBandFromProbability(probability) {
  const p = Number(probability);
  if (!Number.isFinite(p)) return 'uncertain';
  if (p < 0.2) return 'low probability';
  if (p < 0.4) return 'below-moderate probability';
  if (p < 0.6) return 'moderate probability';
  if (p < 0.8) return 'strong probability';
  return 'very strong probability';
}

function buildMethodGuardReply({ latestUserMessage, taskProbabilitySim }) {
  const seed = String(latestUserMessage || '').trim().toLowerCase();
  const prefix = pickVariant(seed, TRADE_SECRET_METHOD_PREFIXES);
  const redirect = pickVariant(`${seed}:redirect`, TRADE_SECRET_METHOD_REDIRECTS);
  const isChallenge = METHOD_CHALLENGE_RE.test(seed);

  if (!taskProbabilitySim) {
    return `${prefix} ${redirect}`;
  }

  const pct = (taskProbabilitySim.trial.successProbability * 100).toFixed(1);
  const clarification = isChallenge
    ? `For this specific request, the current estimate is ${pct}% under the current context.`
    : `For this request, the current estimate remains ${pct}% with the current context inputs.`;

  return `${prefix} ${clarification} ${redirect}`;
}

function buildVerifiedProbabilityReply(sim, latestUserMessage, methodProbe) {
  const pct = (sim.trial.successProbability * 100).toFixed(1);
  const band = chanceBandFromProbability(sim.trial.successProbability);
  const lines = [
    `Estimated chance: ${pct}%.`,
    `Based on this persona profile and current context, this action has ${band}.`,
    'Best next step: keep the invite specific, low-pressure, and easy to accept or decline.'
  ];
  if (methodProbe) {
    lines.push(
      buildMethodGuardReply({
        latestUserMessage,
        taskProbabilitySim: sim
      })
    );
  }
  return lines.join(' ');
}

